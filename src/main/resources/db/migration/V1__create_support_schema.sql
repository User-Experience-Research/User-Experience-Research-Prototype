CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(80) NOT NULL UNIQUE,
    display_name VARCHAR(160) NOT NULL,
    email VARCHAR(240) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    description VARCHAR(800) NOT NULL,
    keywords VARCHAR(1000) NOT NULL
);

CREATE TABLE facilities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    summary VARCHAR(1200) NOT NULL,
    provider VARCHAR(200) NOT NULL,
    location VARCHAR(240) NOT NULL,
    distance_minutes INTEGER NOT NULL,
    rating DECIMAL(3, 2) NOT NULL,
    response_time VARCHAR(160) NOT NULL,
    contact_mode VARCHAR(240) NOT NULL,
    eligibility VARCHAR(500) NOT NULL,
    preparation VARCHAR(700) NOT NULL,
    tags VARCHAR(1000) NOT NULL
);

CREATE TABLE facility_categories (
    facility_id BIGINT NOT NULL REFERENCES facilities(id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
    PRIMARY KEY (facility_id, category_id)
);

CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    facility_id BIGINT NOT NULL REFERENCES facilities(id),
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(30) NOT NULL,
    note VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT appointment_status CHECK (status IN ('BOOKED', 'CANCELLED', 'COMPLETED'))
);

CREATE TABLE conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE conversation_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    role VARCHAR(20) NOT NULL,
    content VARCHAR(6000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT conversation_role CHECK (role IN ('USER', 'ASSISTANT', 'TOOL'))
);

CREATE INDEX idx_facility_categories_category ON facility_categories(category_id);
CREATE INDEX idx_appointments_user ON appointments(user_id, starts_at);
CREATE INDEX idx_conversations_user ON conversations(user_id, updated_at);

